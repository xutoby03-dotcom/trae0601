export const getSampleById = (id: string) =>
  TEST_SAMPLES.find((s) => s.id === id);

export const getChainById = (id: string) =>
  EVOLUTION_CHAINS.find((c) => c.id === id);

export const getSamplesByChain = (chainId: string) =>
  TEST_SAMPLES.filter((s) => s.evolutionChainId === chainId).sort(
    (a, b) => a.version - b.version
  );
