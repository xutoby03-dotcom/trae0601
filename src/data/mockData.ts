export const mockNotifications: Notification[] = mockInspections
  .filter((i) => i.status === 'notified' || i.status === 'overdue' || i.status === 'recheck')
  .map((inspection, index) => {
    const baseDays = inspection.status === 'overdue' ? 7 : inspection.status === 'recheck' ? 10 : 3;
    const deadline = new Date(
      new Date(inspection.updatedAt).getTime() + baseDays * 24 * 60 * 60 * 1000
    ).toISOString();

    return {
      id: generateId(),
      inspectionId: inspection.id,
      method: (['上门', '电话', '微信', '告示'] as const)[index % 4],
      deadline,
      contactPerson: inspection.suspectedResident,
      contactPhone: `138${String(10000000 + index * 12345).slice(0, 8)}`,
      feedback: index % 3 === 0 ? '知道了，马上清理' : undefined,
      feedbackAt: index % 3 === 0 ? daysAgo(2) : undefined,
      status: (inspection.status === 'overdue' || inspection.status === 'recheck')
        ? 'overdue'
        : index % 3 === 0
        ? 'feedback_received'
        : 'sent',
      createdAt: inspection.updatedAt,
      noticeCount: inspection.recheckCount || 0 > 0 ? 2 : 1,
    };
  });

