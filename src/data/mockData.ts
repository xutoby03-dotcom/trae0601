export function generateVisitPlansForCase(caseId: string, dischargeDate: string): VisitPlan[] {
  return [1, 3, 7].map((day) => ({
    id: generateId(),
    caseId,
    dayNumber: day as 1 | 3 | 7,
    planDate: addDaysToString(dischargeDate, day),
    status: 'pending' as const,
  }));
}
