function cagePhoto(species: string): string {
  const prompts: Record<string, string> = {
    mouse: "laboratory%20mice%20in%20clean%20cage%20with%20bedding%20material",
    zebrafish: "zebrafish%20in%20laboratory%20aquarium%20tank%20with%20blue%20water",
    rat: "laboratory%20rats%20in%20enriched%20cage",
    rabbit: "laboratory%20rabbit%20in%20clean%20cage",
  };
  return `https://trae-api-cn.mchost.guru/api/ide/v1/text_to_image?prompt=${prompts[species] || "laboratory%20animal%20cage"}&image_size=square`;
}

