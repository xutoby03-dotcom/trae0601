const now = new Date();
const daysAgo = (d: number) => {
  const date = new Date(now);
  date.setDate(date.getDate() - d);
  return date.toISOString();
};
const hoursAgo = (h: number) => {
  const date = new Date(now);
  date.setHours(date.getHours() - h);
  return date.toISOString();
};
const hoursLater = (h: number) => {
  const date = new Date(now);
  date.setHours(date.getHours() + h);
  return date.toISOString();
};

