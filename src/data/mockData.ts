const now = new Date();
const daysAgo = (d: number) => {
  const n = new Date(now);
  n.setDate(n.getDate() - d);
  return n.toISOString();
};
const daysLater = (d: number) => {
  const n = new Date(now);
  n.setDate(n.getDate() + d);
  return n.toISOString();
};

