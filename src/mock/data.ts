const generateFurnitureId = (roomIdx: number, index: number, type: string) => {
  const roomCodes = ['A', 'B', 'C', 'D'];
  const roomCode = roomCodes[roomIdx] || String(roomIdx + 1);
  const typeCode = type === 'table' ? 'T' : 'C';
  return `FJ-${roomCode}-${typeCode}${String(index).padStart(2, '0')}`;
};

