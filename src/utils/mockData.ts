const pastDate = (daysAgo: number) => {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  return date.toISOString();
};

const futureDate = (daysLater: number) => {
  const date = new Date();
  date.setDate(date.getDate() + daysLater);
  return date.toISOString();
};

