export const generateMockBoardItems = (fabrics: Fabric[], boards: Board[]): BoardItem[] => {
  const items: BoardItem[] = [];
  const board1Fabrics = fabrics.slice(0, 3);
  const board2Fabrics = fabrics.slice(6, 9);

  board1Fabrics.forEach((fabric, index) => {
    items.push({
      id: generateId(),
      fabricId: fabric.id,
      boardId: boards[0].id,
      order: index,
      addedAt: now,
    });
  });

  board2Fabrics.forEach((fabric, index) => {
    items.push({
      id: generateId(),
      fabricId: fabric.id,
      boardId: boards[1].id,
      order: index,
      addedAt: now,
    });
  });

  return items;
};
